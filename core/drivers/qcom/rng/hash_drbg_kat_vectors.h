enum hash_drbg_kat_op_id {
	HASH_DRBG_KAT_OP_INSTANTIATE,
	HASH_DRBG_KAT_OP_GENERATE,
	HASH_DRBG_KAT_OP_RESEED,
};

struct hash_drbg_kat_instantiate_op {
	const uint8_t *entropy;
	size_t entropy_len;
	const uint8_t *nonce;
	size_t nonce_len;

	const uint8_t *V;
	const uint8_t *C;
	uint64_t reseed_counter;
};

struct hash_drbg_kat_generate_op {
	const uint8_t *output;
	size_t output_len;

	const uint8_t *V;
	const uint8_t *C;
	uint64_t reseed_counter;

	const uint8_t *additional_input;
	size_t additional_input_len;
};

struct hash_drbg_kat_reseed_op {
	const uint8_t *entropy;
	size_t entropy_len;

	const uint8_t *V;
	const uint8_t *C;
	uint64_t reseed_counter;

	const uint8_t *additional_input;
	size_t additional_input_len;
};

struct hash_drbg_kat_op {
	enum hash_drbg_kat_op_id op;

	union {
		struct hash_drbg_kat_instantiate_op instantiate;
		struct hash_drbg_kat_generate_op generate;
		struct hash_drbg_kat_reseed_op reseed;
	} test;
};

struct hash_drbg_kat_vector {
	const struct hash_drbg_kat_op *ops;
	size_t ops_len;
};

