#ifndef __PTA_SDM_SVC_H
#define __PTA_SDM_SVC_H

#include <util.h>

#define PTA_SDM_SVC_UUID \
	{ 0xb68b0d3b, 0x5ef5, 0x4f4e, \
	  { 0xac, 0x23, 0x00, 0x00, 0x5e, 0xd3, 0x00, 0x65 } }

#define PTA_SDM_SVC_API_VERSION		20

#define SDM_PHASE2_STATUS_SUCCESS	0U
#define SDM_PHASE2_STATUS_NOP		1U
#define SDM_PHASE2_STATUS_SKIPPED	2U
#define SDM_PHASE2_STATUS_FAILED	3U

#define PTA_CMD_GET_VERSION		0x0
#define PTA_CMD_SDM_GET_ID_CODE		0x1
#define PTA_CMD_SDM_GET_CHIP_ID		0x2
#define PTA_CMD_SDM_SDOS_CRYPT		0x3
#define PTA_CMD_SDM_GET_RANDOM		0x4

/* Minimum: 1 word, 4-byte aligned */
#define SDM_RNG_MIN_BYTES		4U
/* 1020 words (FCS_RANDOM_EXT_MAX_WORD_SIZE * 4) */
#define SDM_RNG_MAX_BYTES		4080U

#define PTA_CMD_SDM_SEND_CERT		0x5
#define SDM_CERT_MAX_SIZE		4096U
#define SDM_CERT_MAGIC_NUM		0x25D04E7FU
#define SDM_CERT_MIN_HDR_BYTES		0x20U
#define SDM_CERT_OFF_MAGIC		0x00U
#define SDM_CERT_OFF_TYPE		0x0CU
#define SDM_CERT_OFF_COUNTER		0x18U
#define SDM_CERT_OFF_ID			0x1CU

/* SDOS / service root key */
#define SDM_CERT_TYPE_CANCEL_SDOS_ROOT	0x0BU
/* user AES root key */
#define SDM_CERT_TYPE_CANCEL_AES_ROOT	0x0DU
/* counter update or KEY-ID cancel */
#define SDM_CERT_TYPE_COUNTER		0x05U

#define SDM_CERT_COUNTER_TYPE_MASK	0xFFU
#define SDM_CERT_COUNTER_KEYID_CANCEL	0U
/* cancel owner root-hash slot */
#define SDM_CERT_COUNTER_ROOT_HASH_CANCEL 255U

#define SDM_CERT_KEY_OWNER_SHIFT	8U
#define SDM_CERT_KEY_OWNER_MASK		0xFFU

#define PTA_CMD_SDM_GET_PROV_DATA	0x6
#define SDM_PROV_MAX_HASHES		8U
/* secp384r1: 384 bits = 12 uint32_t */
#define SDM_PROV_HASH_WORDS		12U
#define SDM_PROV_DATA_MAX_SIZE		512U

#define SDM_PROV_HASH_COUNT(cosign) \
	((((cosign) >> 8) & 0xFFU) + 1U)
#define SDM_PROV_HASH_TYPE(cosign)	((cosign) & 0xFFU)

#define PTA_CMD_SDM_READ_USER_FUSES	0x7
#define PTA_CMD_SDM_PROG_USER_FUSES	0x8
#define SDM_USER_FUSE_COUNT		16U
#define SDM_USER_FUSE_SIZE		(SDM_USER_FUSE_COUNT * 4U)

#define SDM_EFUSE_READ_CMD		0x2DU
#define SDM_EFUSE_PROG_CMD		0x2CU
#define SDM_EFUSE_READ_PAYLOAD_SIZE	4U
#define SDM_EFUSE_PROG_PAYLOAD_SIZE	72U
#define SDM_EFUSE_RESP_BUF_SIZE		0x400U
#define SDM_EFUSE_READ_CMD_WORD		0x00001000U
#define SDM_EFUSE_PROG_MAGIC		0x55736572U

#define PTA_CMD_SDM_PROG_PUBKEY		0x9
#define SDM_PUBKEY_HASH_SIZE_SHA256	32U
#define SDM_PUBKEY_HASH_SIZE_SHA384	48U

#define PTA_CMD_SDM_EFUSE_RELOAD_CACHE	0xA
#define PTA_CMD_SDM_SECURITY_OP		0xB

#define SDM_SECOPT_FIRMWARE_JOINT_SIGNING	BIT(0)
#define SDM_SECOPT_AES_KEY_UPDATE_MODE		BIT(1)
#define SDM_SECOPT_JTAG_DISABLE			BIT(2)
#define SDM_SECOPT_HPS_DEBUG_DISABLE		BIT(3)
#define SDM_SECOPT_VIRTUAL_EFUSE_DISABLE	BIT(4)
#define SDM_SECOPT_HPS_ZEROIZATION		BIT(5)
#define SDM_SECOPT_FPGA_ZEROIZATION		BIT(6)
#define SDM_SECOPT_PUF_AES_KEY_DISABLE		BIT(7)
#define SDM_SECOPT_BBRAM_AES_KEY_DISABLE	BIT(8)
#define SDM_SECOPT_EFUSE_AES_KEY_DISABLE	BIT(9)
#define SDM_SECOPT_PUF_ENROLLMENT_DISABLE	BIT(10)
#define SDM_SECOPT_SECURE_CLOCK_ONLY		BIT(11)
#define SDM_SECOPT_CRC_ENABLE			BIT(12)
#define SDM_SECOPT_ALIASL1_DISABLE		BIT(16)
#define SDM_SECOPT_DISABLE_BETA_MODE		BIT(17)
#define SDM_SECOPT_TEST_MODE			BIT(31)

#define SDM_SECOPT_VALID_MASK ( \
	SDM_SECOPT_FIRMWARE_JOINT_SIGNING | \
	SDM_SECOPT_AES_KEY_UPDATE_MODE | \
	SDM_SECOPT_JTAG_DISABLE | \
	SDM_SECOPT_HPS_DEBUG_DISABLE | \
	SDM_SECOPT_VIRTUAL_EFUSE_DISABLE | \
	SDM_SECOPT_HPS_ZEROIZATION | \
	SDM_SECOPT_FPGA_ZEROIZATION | \
	SDM_SECOPT_PUF_AES_KEY_DISABLE | \
	SDM_SECOPT_BBRAM_AES_KEY_DISABLE | \
	SDM_SECOPT_EFUSE_AES_KEY_DISABLE | \
	SDM_SECOPT_PUF_ENROLLMENT_DISABLE | \
	SDM_SECOPT_SECURE_CLOCK_ONLY | \
	SDM_SECOPT_CRC_ENABLE | \
	SDM_SECOPT_ALIASL1_DISABLE | \
	SDM_SECOPT_DISABLE_BETA_MODE | \
	SDM_SECOPT_TEST_MODE)

#define SDM_SECOPT_HOST_FLAG_NON_VOLATILE	BIT(0)
#define SDM_SECOPT_HOST_FLAGS_VALID_MASK \
	SDM_SECOPT_HOST_FLAG_NON_VOLATILE

#define PTA_CMD_SDM_DISABLE_OWNED_ENTRY	0xC
#define SDM_DEO_HOST_FLAG_NON_VOLATILE	BIT(0)
#define SDM_DEO_HOST_FLAGS_VALID_MASK \
	SDM_DEO_HOST_FLAG_NON_VOLATILE

#define PTA_CMD_SDM_EFUSE_WRITE_DISABLE	0xD
#define PTA_CMD_SDM_NS_ALLOWED_LIST_DEACTIVATE	0xE
#define PTA_CMD_SDM_NS_ALLOWED_LIST_REMOVE	0xF

/* 10 words: 2 hdr + 8 hash */
#define SDM_PUBKEY_PAYLOAD_SIZE_SECP256R1	40U
/* 14 words: 2 hdr + 12 hash */
#define SDM_PUBKEY_PAYLOAD_SIZE_SECP384R1	56U

#define SDM_PUBKEY_WORD_BYTES		4U
#define SDM_PUBKEY_HASH_OFFSET		8U
#define SDM_PUBKEY_MAX_HASHES_PER_CALL	5U
#define SDM_PUBKEY_HASH_TYPE_SECP256R1	1U
#define SDM_PUBKEY_HASH_TYPE_SECP384R1	2U

/* T: cache-only, no fuse burn */
#define SDM_PUBKEY_FLAG_TEST		BIT(31)
/* S: skip cancel (dev only) */
#define SDM_PUBKEY_FLAG_SKIP_CANCEL	BIT(30)
#define SDM_PUBKEY_FLAG_KEY_COUNT_SHIFT	8U
#define SDM_PUBKEY_FLAG_KEY_COUNT_MASK \
	(0xFFU << SDM_PUBKEY_FLAG_KEY_COUNT_SHIFT)

#define SDM_PUBKEY_FLAG_KEY_COUNT(k) \
	((((uint32_t)(k) - 1U) << SDM_PUBKEY_FLAG_KEY_COUNT_SHIFT) & \
	 SDM_PUBKEY_FLAG_KEY_COUNT_MASK)

#define SDM_PUBKEY_HOST_FLAG_NON_VOLATILE	BIT(0)
#define SDM_PUBKEY_HOST_FLAGS_VALID_MASK \
	SDM_PUBKEY_HOST_FLAG_NON_VOLATILE

/* test=1 (virtual) */
#define SDM_EFUSE_PROG_CTRL_WORD	0x80001000U
/* test=0 (eFuse burn) */
#define SDM_EFUSE_PROG_CTRL_WORD_BURN	0x00001000U

#define SDM_USER_FUSES_HOST_FLAG_NON_VOLATILE	BIT(0)

#define PTA_SDM_SVC_CRYPT_DECRYPT	0
#define PTA_SDM_SVC_CRYPT_ENCRYPT	1

#define SDOS_HDR_SIZE			40
/* SDM auth/IV overhead */
#define SDOS_HMAC_SIZE			48
#define SDOS_ENCRYPT_IN_MAGIC		0xACBDBDEDU
#define SDOS_ENCRYPT_OUT_MAGIC		0x53424212U
#define SDOS_HDR_PAD_MAGIC		0x01020304U

#define SDOS_PAD_LEN(n)			((32U - ((n) & 31U)) & 31U)

#define SDOS_MIN_DATA_LEN		32U
/* 32672 bytes */
#define SDOS_MAX_DATA_LEN		(32U * 1024U - 96U)

#define SDOS_FLAGS(asoi, srk_index, pad_len) \
	(((uint32_t)(asoi) << 16) | \
	 ((uint32_t)(srk_index) << 8) | \
	 (uint32_t)(pad_len))

#endif /* __PTA_SDM_SVC_H */
